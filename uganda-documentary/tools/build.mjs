#!/usr/bin/env node
/**
 * Builds the film from the narration timings.
 *
 *   script.json          what is said, chapter by chapter (hand-written)
 *   data/chapters.json   when each chapter starts and how long it runs (voice.py)
 *   data/lines.json      when each line is spoken (voice.py)
 *   cues.json            sound effects and where they land (hand-written)
 *   src/film.template.html   the three.js scene, with placeholders
 *
 * Writes index.html and compositions/film.html. Never hand-edit those two:
 * they are regenerated every time the voice changes.
 *
 *   node tools/build.mjs
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const read = (p) => JSON.parse(readFileSync(p, "utf8"));
const script = read("script.json");
const chapters = read("data/chapters.json");
const lines = read("data/lines.json");
const cues = existsSync("cues.json") ? read("cues.json") : [];

// The six dioramas sit on the timeline road, 95 m apart, in chapter order.
const Z = [0, -95, -190, -285, -380, -475];

const endStart = +(chapters[chapters.length - 1].start +
  chapters[chapters.length - 1].duration).toFixed(2);
const duration = +(endStart + 4.4).toFixed(2);

// ---------------------------------------------------------------------------
// Chapter table handed to the scene
// ---------------------------------------------------------------------------
const table = chapters.map((c, i) => ({
  start: +c.start.toFixed(3),
  dur: +c.duration.toFixed(3),
  z: Z[i] ?? -95 * i,
  num: c.num,
  title: c.title,
  key: c.key
}));

// ---------------------------------------------------------------------------
// Chapter clips. One per chapter, same ids the timeline expects.
// ---------------------------------------------------------------------------
const esc = (s) => String(s);
const clips = table
  .map(
    (c, i) => `  <div id="film-b${i + 1}" class="beat clip" data-hf-id="hf-b${i + 1}"
       data-start="${c.start}" data-duration="${c.dur}">
    <div class="beat-inner">
      <span id="film-b${i + 1}-num" class="beat-num" data-hf-id="hf-b${i + 1}-num">${esc(c.num)} &middot; ${esc(script.chapters[i].date)}</span>
      <h1 id="film-b${i + 1}-title" class="beat-title" data-hf-id="hf-b${i + 1}-title">${esc(c.title)}</h1>
      <span id="film-b${i + 1}-date" class="beat-date" data-hf-id="hf-b${i + 1}-date">${esc(c.key.toUpperCase())}</span>
      <span id="film-b${i + 1}-rule" class="beat-rule" data-hf-id="hf-b${i + 1}-rule"></span>
    </div>
  </div>`
  )
  .join("\n\n");

const titleCard = `  <div id="film-t0" class="clip" data-hf-id="hf-t0" data-start="0" data-duration="${chapters[0].start}">
    <div class="title-card">
      <span id="film-t0-word" class="word" data-hf-id="hf-t0-word">Uganda</span>
      <span id="film-t0-sub" class="sub" data-hf-id="hf-t0-sub">A history in six beats</span>
    </div>
  </div>`;

// ---------------------------------------------------------------------------
// Composition
// ---------------------------------------------------------------------------
let film = readFileSync("src/film.template.html", "utf8");
const fill = (text, token, value) => text.split(token).join(String(value));
film = fill(film, "__DURATION__", duration);
film = fill(film, "__CHAPTERS__", JSON.stringify(table, null, 1));
film = fill(film, "__CLIPS__", titleCard + "\n\n" + clips);
film = fill(film, "__END_START__", (endStart + 0.15).toFixed(2));
film = fill(film, "__END_DUR__", (duration - endStart - 0.15).toFixed(2));

writeFileSync("compositions/film.html", film);

// ---------------------------------------------------------------------------
// Root: hosts, narration, score, cues
// ---------------------------------------------------------------------------
const resolveCue = (cue) => {
  if (typeof cue.chapter === "number") return chapters[cue.chapter].start;
  if (typeof cue.line === "number") return lines[cue.line].start;
  if (cue.text) {
    const hit = lines.find((l) => l.text.toLowerCase().includes(cue.text.toLowerCase()));
    if (!hit) {
      console.warn(`  cue text not found: "${cue.text}"`);
      return null;
    }
    return hit.start;
  }
  return null;
};

const cueTags = cues
  .map((cue, i) => {
    const at = resolveCue(cue);
    if (at === null) return null;
    const start = Math.max(0, +(at + (cue.offset || 0)).toFixed(3));
    const vol = cue.volume ?? 0.4;
    const fadeOut = cue.fadeOut ?? Math.min(1.2, (cue.dur || 2) * 0.4);
    return `  <audio id="cue-${i + 1}" data-hf-id="hf-cue-${i + 1}" src="assets/sfx/${cue.file}"
         data-start="${start}" data-duration="${cue.dur || 2}" data-volume="${vol}"
         data-fade-out="${fadeOut}"></audio>`;
  })
  .filter(Boolean)
  .join("\n");

const root = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Uganda — A History in Six Beats</title>
<!--
  Generated by tools/build.mjs from script.json + data/chapters.json.
  Do not hand-edit this file: edit the script or the template and rebuild.

  Video: 2 minutes, 1920x1080, 30 fps. Three.js from unpkg, low-poly models
  hotlinked from the polyfork.dev CDN, flag from the official SVG raster.
  Voice: edge-tts en-KE-ChilembaNeural. Score: tools/score.mjs. Cues: Mixkit
  recordings, see CREDITS.md.
-->
<script src="assets/gsap.min.js"></script>
<script type="importmap">
{
  "imports": {
    "three": "https://unpkg.com/three@0.180.0/build/three.module.js",
    "three/addons/": "https://unpkg.com/three@0.180.0/examples/jsm/"
  }
}
</script>
<style>
  html, body { margin: 0; padding: 0; background: #0d0a10; }
  #root { position: relative; width: 1920px; height: 1080px; overflow: hidden; background: #0d0a10; }
</style>
</head>
<body>
<div id="root"
     data-hf-id="hf-root"
     data-composition-id="main"
     data-start="0"
     data-duration="${duration}"
     data-width="1920"
     data-height="1080"
     data-fps="30">

  <div id="film"
       data-hf-id="hf-film"
       data-composition-id="film"
       data-composition-src="compositions/film.html"
       data-start="0"
       data-duration="${duration}"
       data-track-index="1"
       data-track-kind="graphics"
       data-width="1920"
       data-height="1080"></div>

  <!-- Narration: the voice the whole cut is timed to. -->
  <audio id="narration"
         data-hf-id="hf-narration"
         src="data/narration.m4a"
         data-start="0"
         data-duration="${duration}"></audio>

  <!-- Score: a slow pad under the voice, generated by tools/score.mjs. -->
  <audio id="score"
         data-hf-id="hf-score"
         src="assets/score.wav"
         data-start="0"
         data-duration="${duration}"
         data-volume="0.30"></audio>

  <!-- Sound cues -->
${cueTags}
</div>
<script>
  window.__timelines = window.__timelines || {};
  window.__timelines["main"] = gsap.timeline({ paused: true });
</script>
</body>
</html>
`;

writeFileSync("index.html", root);

console.log(`built: ${duration}s, ${table.length} chapters, ${cues.length} cues`);
for (const c of table) {
  console.log(`  ${c.num} ${c.title.padEnd(16)} ${String(c.start).padStart(6)}s  +${c.dur}s`);
}
console.log(`  end card at ${endStart + 0.15}s`);
